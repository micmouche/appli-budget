export interface CategorizeInput {
  label: string;
  /** Règles apprises : libellé normalisé (ou préfixe) → catégorie. */
  learned: ReadonlyMap<string, string>;
  fallback: string;
}

export function categorize({ label, learned, fallback }: CategorizeInput): {
  categoryId: string;
  source: 'learned' | 'keyword' | 'fallback';
} {
  const norm = normalizeLabel(label);
  if (learned.has(norm)) return { categoryId: learned.get(norm)!, source: 'learned' };
  for (const [pattern, categoryId] of learned) {
    if (pattern.length >= 4 && norm.startsWith(pattern)) return { categoryId, source: 'learned' };
  }
  const padded = ` ${norm} `;
  for (const [kw, categoryId] of KEYWORDS) {
    if (padded.includes(` ${kw.trim()} `) || (kw.endsWith(' ') && padded.includes(` ${kw}`)))
      return { categoryId, source: 'keyword' };
  }
  return { categoryId: fallback, source: 'fallback' };
}

/** Clé d'apprentissage : les 3 premiers mots du libellé normalisé (assez pour un commerçant, pas trop pour généraliser). */
export function learningKey(label: string): string {
  return normalizeLabel(label).split(' ').slice(0, 3).join(' ');
}
